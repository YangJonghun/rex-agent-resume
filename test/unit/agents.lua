local t = require("unit.lib")
local util = require("rex-agent-resume.util")
local agents = require("rex-agent-resume.agents")
local eq, env, no_env, files = t.eq, t.env, t.no_env, t.files

local function parse(agent, data, getenv) return (agents.parse(agents.specs[agent], data, getenv or no_env)) end
local function resume(agent, id)
  local argv = agents.resume_argv(agents.specs[agent], id)
  return argv and util.shell_join(argv)
end

eq(parse("claude", { hook_event_name = "SessionStart", session_id = "c1" }), "c1", "claude session start")
eq(parse("claude", { hook_event_name = "SessionStart", session_id = "c1", agent_id = "sub" }), nil, "claude subagent ignored")
eq(parse("claude", { hook_event_name = "Stop", session_id = "c1" }), nil, "claude other event ignored")
eq(parse("claude", { hook_event_name = "SessionStart", session_id = "c1" }, env({ CURSOR_VERSION = "1" })), nil, "cursor running claude hooks ignored")
eq(parse("codex", { session_id = "x1" }), nil, "codex needs transcript_path")
eq(parse("codex", { session_id = "x1", transcript_path = "/t" }), "x1", "codex session")
eq(parse("codex", { session_id = "x1", transcript_path = "/t" }, env({ CODEX_THREAD_ID = "x2" })), nil, "codex child thread ignored")
eq(parse("copilot", { sessionId = "p1" }), "p1", "copilot camelCase id")
eq(parse("copilot", { sessionId = "p1", prompt = "hi" }), nil, "copilot prompt event ignored")
eq(parse("letta", { conversation_id = "default", agent_id = "a1" }), "default:a1", "letta default conversation")
eq(parse("letta", { conversation_id = "default" }), nil, "letta default without agent")
eq(parse("grok", { hook_event_name = "session_start", session_id = "g1" }, env({ GROK_SESSION_ID = "g2" })), "g2", "grok env wins")
eq(parse("cursor", { hook_event_name = "sessionStart", conversationId = "k1" }), "k1", "cursor conversation id")
eq(parse("antigravity-cli", { hook_event_name = "PreInvocation", conversationId = "y1" }), "y1", "antigravity conversation")
eq(parse("antigravity-cli", { hook_event_name = "SomethingElse", conversationId = "y1" }), "y1", "antigravity takes any event, like herdr")
eq(parse("droid", { session_id = "bad\nid" }), nil, "control characters rejected")

eq(resume("claude", "c1"), "claude --resume c1", "claude resume")
eq(resume("codex", "x1"), "codex --no-daemon resume x1", "codex resumes without the shared daemon")
eq(select(2, agents.parse(agents.specs.claude, { hook_event_name = "SessionStart", session_id = "c1", transcript_path = "/t/c1.jsonl" }, no_env)), "/t/c1.jsonl", "transcript path comes with the id")
eq(resume("copilot", "p1"), "copilot --resume=p1", "copilot resume")
eq(resume("cursor", "k1"), "cursor-agent --resume k1", "cursor resume")
eq(resume("antigravity-cli", "y1"), "agy --conversation y1", "antigravity resume")
eq(resume("letta", "default:a1"), "letta --conversation default --agent a1", "letta default resume")
eq(resume("letta", "default:"), nil, "letta default without agent")

eq(select(2, agents.discover("claude --dangerously-skip-permissions", 42, files({ ["/h/.claude/sessions/42.json"] = { sessionId = "s42" } }), no_env, "/h")), "s42", "running claude found from its sessions file")
eq(select(2, agents.discover("/usr/local/bin/claude", 42, files({ ["/c/sessions/42.json"] = { sessionId = "s43" } }), env({ CLAUDE_CONFIG_DIR = "/c" }), "/h")), "s43", "CLAUDE_CONFIG_DIR is honored")
eq(select(2, agents.discover("claude --resume s44", 7, files({}), no_env, "/h")), "s44", "claude without a sessions file falls back to its command line")
eq(select(2, agents.discover("codex --yolo resume x9", 7, files({}), no_env, "/h")), "x9", "running codex found from its resume command")
eq(agents.discover("codex resume --last", 7, files({}), no_env, "/h"), nil, "a flag is never taken for a session id")
eq(select(2, agents.discover("node /opt/lib/codex resume x8", 7, files({}), no_env, "/h")), "x8", "an agent run through node is recognized")
eq(select(2, agents.discover("copilot --resume=p9", 7, files({}), no_env, "/h")), "p9", "flag with an attached id")
eq(agents.discover("codex --yolo", 7, files({}), no_env, "/h"), nil, "a fresh codex cannot be identified")
eq(agents.discover("vim notes.md", 7, files({}), no_env, "/h"), nil, "other programs are not agents")
