local merge = agents.merge_report
local running_claude = { agent = "claude", id = "c1", pid = 7 }
eq(merge(running_claude, { agent = "claude", id = "c2", source = "clear" }, 7, true).id, "c2", "claude switches session on /clear")
eq(merge(running_claude, { agent = "claude", id = "c2", source = "startup" }, 7, true).id, "c1", "but keeps it for an unexplained new id")
eq(merge({ agent = "copilot", id = "p1", pid = 7 }, { agent = "copilot", id = "p2", source = "resume" }, 7, true).id, "p1", "copilot keeps its first session, like herdr")
eq(merge(running_claude, { agent = "claude", id = "c2", source = "startup" }, 8, true).id, "c2", "a new process starts fresh")
local running_opencode = { agent = "opencode", id = "o1", pid = 7 }
eq(merge(running_opencode, { agent = "opencode", id = "o2", source = "select" }, 7, true).id, "o2", "opencode follows the selected session")
eq(merge(running_opencode, { agent = "opencode", id = "o2" }, 7, true).id, "o1", "but not a session seen by its server plugin")
eq(merge({ agent = "kilo", id = "k1", pid = 7 }, { agent = "kilo", id = "k2", source = "startup" }, 7, true).id, "k1", "kilo keeps its first session, like herdr")
eq(merge({ agent = "pi", id = "/s/a.jsonl", pid = 7 }, { agent = "pi", id = "/s/b.jsonl" }, 7, true).id, "/s/b.jsonl", "pi session files always replace")
eq(merge({ agent = "pi", id = "p1", pid = 7 }, { agent = "pi", id = "p2", source = "startup" }, 7, true).id, "p1", "pi ids follow replace_on")
local fresh = { agent = "claude", id = "new", transcript = "/t/new.jsonl", source = "clear" }
eq(merge(nil, fresh, 7, true).id, "new", "a session with a transcript is resumable")
eq(merge(nil, fresh, 7, false).id, nil, "a session without a transcript is not resumable yet")
eq(merge(nil, fresh, 7, false).pending.id, "new", "and waits as pending")
eq(merge({ agent = "claude", id = "old", pid = 7 }, fresh, 7, false).id, "old", "the same agent keeps its last resumable session")
eq(merge({ agent = "claude", id = "old" }, fresh, 7, false).id, "old", "including the one we just resumed")
eq(merge({ agent = "claude", id = "old", pid = 6 }, fresh, 7, false).id, nil, "a new agent does not inherit a quit agent's session")
local waiting = merge({ agent = "claude", id = "old", pid = 7 }, fresh, 7, false)
eq(agents.promote(waiting, function() return false end), false, "pending stays until the transcript exists")
eq(agents.promote(waiting, function() return true end) and waiting.id, "new", "then it becomes the resumable session")
